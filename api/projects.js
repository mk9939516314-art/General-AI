const applications = [];

export default async function handler(req, res) {
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Methods', 'GET,POST,OPTIONS');
    res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');

    if (req.method === 'OPTIONS') {
        return res.status(200).end();
    }

    const { url, method } = req;
    const path = url.split('?')[0];

    try {
        // Apply for project
        if (method === 'POST' && path.endsWith('/apply')) {
            const { projectId, userEmail, accountId, experienceYears } = req.body || {};

            if (!projectId || (!userEmail && !accountId)) {
                return res.status(400).json({ success: false, message: 'Missing required application details.' });
            }

            const project = PROJECTS.find(p => p.id === projectId);
            if (!project) {
                return res.status(404).json({ success: false, message: 'Project not found.' });
            }

            const appRecord = {
                id: 'APP-' + Math.floor(10000 + Math.random() * 90000),
                projectId,
                projectTitle: project.title,
                userEmail,
                accountId,
                experienceYears: experienceYears || '3+',
                status: 'Under Review',
                appliedAt: new Date().toISOString()
            };

            applications.push(appRecord);

            return res.status(200).json({
                success: true,
                message: `Application submitted successfully for ${project.title}!`,
                application: appRecord
            });
        }

        // Get All Projects (with optional domain filter)
        const domainFilter = req.query?.domain;
        let result = PROJECTS;

        if (domainFilter && domainFilter !== 'All') {
            result = PROJECTS.filter(p => p.domain.toLowerCase() === domainFilter.toLowerCase());
        }

        return res.status(200).json({
            success: true,
            total: result.length,
            projects: result,
            categories: ['All', 'Code', 'Medicine', 'Mathematics', 'Law', 'Linguistics']
        });

    } catch (err) {
        return res.status(500).json({ success: false, message: err.message });
    }
}